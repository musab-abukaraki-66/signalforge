"use client";
import { KeyboardEvent, ReactNode, useRef } from "react";

export function SyntheticBanner() {
  return (
    <p className="banner" role="note"><strong>Synthetic demo data — not real business findings.</strong> Generated by a seeded script; every number describes that generator, not any company.</p>
  );
}

export function Tag({ kind }: { kind: "fact" | "pred" | "scen" }) {
  const t = { fact: "Observed in the data", pred: "Model prediction", scen: "Scenario — your assumptions, not a forecast" }[kind];
  return <span className={`tag ${kind}`}>{t}</span>;
}

export function Kpi({ label, value, help }: { label: string; value: string; help?: string }) {
  return (
    <div className="kpi" title={help}>
      <div className="k">{label}</div>
      <div className="v">{value}</div>
    </div>
  );
}

export function Tabs({ tabs, active, onChange, children, idPrefix = "tab" }: { tabs: { id: string; label: string }[]; active: string; onChange: (id: string) => void; children: ReactNode; idPrefix?: string }) {
  const refs = useRef<Record<string, HTMLButtonElement | null>>({});
  const onKey = (e: KeyboardEvent, i: number) => {
    const next = e.key === "ArrowRight" ? (i + 1) % tabs.length : e.key === "ArrowLeft" ? (i - 1 + tabs.length) % tabs.length : e.key === "Home" ? 0 : e.key === "End" ? tabs.length - 1 : -1;
    if (next >= 0) { e.preventDefault(); onChange(tabs[next].id); refs.current[tabs[next].id]?.focus(); }
  };
  return (
    <>
      <div className="tabs" role="tablist" aria-label="Sections">
        {tabs.map((t, i) => (
          <button key={t.id} ref={(el) => { refs.current[t.id] = el; }} role="tab" id={`${idPrefix}-${t.id}`} aria-selected={active === t.id} aria-controls={`${idPrefix}-panel`} tabIndex={active === t.id ? 0 : -1} onClick={() => onChange(t.id)} onKeyDown={(e) => onKey(e, i)}>{t.label}</button>
        ))}
      </div>
      <div role="tabpanel" id={`${idPrefix}-panel`} aria-labelledby={`${idPrefix}-${active}`} tabIndex={0}>{children}</div>
    </>
  );
}
